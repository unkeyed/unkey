package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"strings"

	"github.com/sqlc-dev/plugin-sdk-go/plugin"
	"golang.org/x/text/cases"
	"golang.org/x/text/language"
)

type Options struct {
	Package string `json:"package"`
}

type Generator struct {
	options Options
}

func NewGenerator() *Generator {
	return &Generator{options: Options{Package: "db"}}
}

func (g *Generator) Configure(options []byte) error {
	if len(options) == 0 {
		return nil
	}
	if err := json.Unmarshal(options, &g.options); err != nil {
		return fmt.Errorf("parse transactional batch plugin options: %w", err)
	}
	if g.options.Package == "" {
		g.options.Package = "db"
	}
	return nil
}

func (g *Generator) Generate(req *plugin.GenerateRequest) (*plugin.GenerateResponse, error) {
	var content strings.Builder
	content.WriteString("// Code generated by sqlc transactional batch statement plugin. DO NOT EDIT.\n\n")
	content.WriteString("package " + g.options.Package + "\n\n")

	generated := 0
	for _, query := range req.GetQueries() {
		enabled, err := hasBatchStatementDirective(query)
		if err != nil {
			return nil, err
		}
		if !enabled {
			continue
		}
		if err := validateBatchStatement(query); err != nil {
			return nil, err
		}
		writeStatementAdapter(&content, query)
		generated++
	}
	if generated == 0 {
		return &plugin.GenerateResponse{Files: nil}, nil
	}

	formatted, err := format.Source([]byte(content.String()))
	if err != nil {
		return nil, fmt.Errorf("format transactional batch output: %w", err)
	}
	return &plugin.GenerateResponse{Files: []*plugin.File{{
		Name:     "transaction_batch_statements_generated.go",
		Contents: formatted,
	}}}, nil
}

const batchStatementDirective = "transactional-batch-statement"

func hasBatchStatementDirective(query *plugin.Query) (bool, error) {
	count := 0
	for _, comment := range query.GetComments() {
		if strings.TrimSpace(comment) == batchStatementDirective {
			count++
		}
	}
	if count > 1 {
		return false, fmt.Errorf("query %q has duplicate %s directives", query.GetName(), batchStatementDirective)
	}
	return count == 1, nil
}

func validateBatchStatement(query *plugin.Query) error {
	if query.GetCmd() != ":exec" && query.GetCmd() != ":execresult" {
		return fmt.Errorf("transactional batch statement %q must use :exec or :execresult", query.GetName())
	}
	if len(query.GetParams()) <= 1 {
		return fmt.Errorf("transactional batch statement %q must use a parameter struct", query.GetName())
	}
	for _, param := range query.GetParams() {
		if param.GetColumn() == nil {
			return fmt.Errorf("transactional batch statement %q has a parameter without column metadata", query.GetName())
		}
	}
	return nil
}

func writeStatementAdapter(content *strings.Builder, query *plugin.Query) {
	functionName := lowerFirst(query.GetName()) + "TransactionBatchStatement"
	content.WriteString(fmt.Sprintf("func %s(params %sParams) transactionBatchStatement {\n", functionName, query.GetName()))
	content.WriteString("\treturn transactionBatchStatement{\n")
	content.WriteString(fmt.Sprintf("\t\tquery: %s,\n", lowerFirst(query.GetName())))
	content.WriteString("\t\targs: []any{\n")
	for _, param := range query.GetParams() {
		content.WriteString(fmt.Sprintf("\t\t\tparams.%s,\n", toCamelCase(param.GetColumn().GetName())))
	}
	content.WriteString("\t\t},\n")
	content.WriteString("\t}\n")
	content.WriteString("}\n\n")
}

func lowerFirst(value string) string {
	if value == "" {
		return value
	}
	return strings.ToLower(value[:1]) + value[1:]
}

var titleCaser = cases.Title(language.English)

func toCamelCase(name string) string {
	var result strings.Builder
	for i, part := range strings.Split(name, "_") {
		switch {
		case part == "id":
			result.WriteString("ID")
		case part == "url" && i > 0:
			result.WriteString("Url")
		default:
			result.WriteString(titleCaser.String(part))
		}
	}
	return result.String()
}
