func TestDeploymentCapabilitiesProtoIsCurrent(t *testing.T) {
	got, err := generate("../../pkg/mysql/types/deployment_capabilities.go", "DeploymentCapabilities", "ctrl.v1", "github.com/unkeyed/unkey/gen/proto/ctrl/v1;ctrlv1")
	require.NoError(t, err)
	want, err := os.ReadFile("../../svc/ctrl/proto/ctrl/v1/deployment_capabilities.proto")
	require.NoError(t, err)
	require.Equal(t, string(want), got, "run mise run generate")
}

func TestGenerateUsesTaggedNamesAndNumbers(t *testing.T) {
	source := writeSource(t, `package example

// Options configure a thing.
type Options struct {
	// Enabled turns the thing on.
	Enabled bool `+"`json:\"enabled\" proto:\"7\"`"+`
	Label string "json:\"display_label,omitempty\" proto:\"2\""
	CountMax uint64 `+"`json:\"count_max\" proto:\"19\"`"+`
}
`)

	got, err := generate(source, "Options", "example.v1", "example.com/gen/example/v1;examplev1")
	require.NoError(t, err)
	require.Equal(t, `// Code generated by tools/generate-proto-message from example.Options. DO NOT EDIT.

syntax = "proto3";

package example.v1;

option go_package = "example.com/gen/example/v1;examplev1";

// Options configure a thing.
message Options {
  // enabled turns the thing on.
  bool enabled = 7;

  string display_label = 2;

  uint64 count_max = 19;
}
`, got)
}

func TestGenerateRejectsInvalidFields(t *testing.T) {
	tests := []struct {
		name   string
		fields string
		errMsg string
	}{
		{name: "duplicate number", fields: "A bool `json:\"a\" proto:\"1\"`\nB bool `json:\"b\" proto:\"1\"`", errMsg: "field number 1 is already used by A"},
		{name: "duplicate name", fields: "A bool `json:\"same\" proto:\"1\"`\nB bool `json:\"same\" proto:\"2\"`", errMsg: "name same is already used by A"},
		{name: "missing tags", fields: "A bool", errMsg: "needs json and proto tags"},
		{name: "missing proto tag", fields: "A bool `json:\"a\"`", errMsg: "proto tag \"\" is not a valid field number"},
		{name: "zero number", fields: "A bool `json:\"a\" proto:\"0\"`", errMsg: "proto tag \"0\""},
		{name: "reserved number", fields: "A bool `json:\"a\" proto:\"19000\"`", errMsg: "proto tag \"19000\""},
		{name: "number too large", fields: "A bool `json:\"a\" proto:\"536870912\"`", errMsg: "proto tag \"536870912\""},
		{name: "non-numeric number", fields: "A bool `json:\"a\" proto:\"one\"`", errMsg: "proto tag \"one\""},
		{name: "missing json name", fields: "A bool `proto:\"1\"`", errMsg: "json name \"\" is not lower_snake_case"},
		{name: "skipped json name", fields: "A bool `json:\"-\" proto:\"1\"`", errMsg: "json name \"-\""},
		{name: "camel case json name", fields: "A bool `json:\"privateNetworking\" proto:\"1\"`", errMsg: "json name \"privateNetworking\""},
		{name: "double underscore json name", fields: "A bool `json:\"private__networking\" proto:\"1\"`", errMsg: "json name \"private__networking\""},
		{name: "leading digit json name", fields: "A bool `json:\"1a\" proto:\"1\"`", errMsg: "json name \"1a\""},
		{name: "int", fields: "A int `json:\"a\" proto:\"1\"`", errMsg: "unsupported type int"},
		{name: "float", fields: "A float64 `json:\"a\" proto:\"1\"`", errMsg: "unsupported type float64"},
		{name: "pointer", fields: "A *bool `json:\"a\" proto:\"1\"`", errMsg: "A: unsupported type"},
		{name: "slice", fields: "A []string `json:\"a\" proto:\"1\"`", errMsg: "A: unsupported type"},
		{name: "unexported", fields: "a bool `json:\"a\" proto:\"1\"`", errMsg: "field must be exported"},
		{name: "embedded", fields: "Base", errMsg: "every field needs exactly one name"},
		{name: "grouped names", fields: "A, B bool `json:\"a\" proto:\"1\"`", errMsg: "every field needs exactly one name"},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			source := writeSource(t, "package example\n\ntype Base struct{}\n\ntype Options struct {\n"+test.fields+"\n}\n")
			_, err := generate(source, "Options", "example.v1", "example.com/gen/example/v1;examplev1")
			require.ErrorContains(t, err, test.errMsg)
		})
	}
}

func writeSource(t *testing.T, src string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "options.go")
	require.NoError(t, os.WriteFile(path, []byte(src), 0o600))
	return path
}
