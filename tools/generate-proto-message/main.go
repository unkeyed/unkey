// Command generate-proto-message writes a proto3 file with one message that
// mirrors a Go struct. Every field must be exported, have a supported scalar
// type, a lower_snake_case `json` name, which becomes the proto field name, and
// a `proto` tag with its field number. Field doc comments are copied.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"reflect"
	"regexp"
	"strconv"
	"strings"
)

var scalarTypes = map[string]string{
	"bool":   "bool",
	"string": "string",
	"int32":  "int32",
	"int64":  "int64",
	"uint32": "uint32",
	"uint64": "uint64",
}

var lowerSnakeCase = regexp.MustCompile(`^[a-z][a-z0-9]*(_[a-z0-9]+)*$`)

func main() {
	source := flag.String("source", "", "Go source file declaring the struct")
	typeName := flag.String("type", "", "struct name")
	protoPackage := flag.String("package", "", "proto package")
	goPackage := flag.String("go-package", "", "go_package option")
	out := flag.String("out", "", "proto file to write")
	flag.Parse()

	src, err := generate(*source, *typeName, *protoPackage, *goPackage)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(src), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(source, typeName, protoPackage, goPackage string) (string, error) {
	file, err := parser.ParseFile(token.NewFileSet(), source, nil, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return "", err
	}

	var doc *ast.CommentGroup
	var structType *ast.StructType
	for _, decl := range file.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.TYPE {
			continue
		}
		for _, spec := range genDecl.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok || typeSpec.Name.Name != typeName {
				continue
			}
			st, ok := typeSpec.Type.(*ast.StructType)
			if !ok {
				return "", fmt.Errorf("%s is not a struct", typeName)
			}
			structType, doc = st, genDecl.Doc
		}
	}
	if structType == nil {
		return "", fmt.Errorf("struct %s not found in %s", typeName, source)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/generate-proto-message from %s.%s. DO NOT EDIT.\n\n", file.Name.Name, typeName)
	fmt.Fprintf(&b, "syntax = \"proto3\";\n\npackage %s;\n\noption go_package = %q;\n\n", protoPackage, goPackage)
	writeComment(&b, "", doc, "", "")
	fmt.Fprintf(&b, "message %s {\n", typeName)

	names := map[string]string{}
	numbers := map[int]string{}
	for i, field := range structType.Fields.List {
		if len(field.Names) != 1 {
			return "", fmt.Errorf("%s: every field needs exactly one name", typeName)
		}
		goName := field.Names[0].Name
		if !field.Names[0].IsExported() {
			return "", fmt.Errorf("%s.%s: field must be exported", typeName, goName)
		}

		ident, ok := field.Type.(*ast.Ident)
		if !ok {
			return "", fmt.Errorf("%s.%s: unsupported type", typeName, goName)
		}
		protoType, ok := scalarTypes[ident.Name]
		if !ok {
			return "", fmt.Errorf("%s.%s: unsupported type %s", typeName, goName, ident.Name)
		}

		if field.Tag == nil {
			return "", fmt.Errorf("%s.%s: needs json and proto tags", typeName, goName)
		}
		rawTag, err := strconv.Unquote(field.Tag.Value)
		if err != nil {
			return "", fmt.Errorf("%s.%s: invalid struct tag: %w", typeName, goName, err)
		}
		tag := reflect.StructTag(rawTag)

		name, _, _ := strings.Cut(tag.Get("json"), ",")
		if !lowerSnakeCase.MatchString(name) {
			return "", fmt.Errorf("%s.%s: json name %q is not lower_snake_case", typeName, goName, name)
		}
		if previous, ok := names[name]; ok {
			return "", fmt.Errorf("%s.%s: name %s is already used by %s", typeName, goName, name, previous)
		}
		names[name] = goName

		number, err := strconv.Atoi(tag.Get("proto"))
		if err != nil || number < 1 || number > 536870911 || (number >= 19000 && number <= 19999) {
			return "", fmt.Errorf("%s.%s: proto tag %q is not a valid field number", typeName, goName, tag.Get("proto"))
		}
		if previous, ok := numbers[number]; ok {
			return "", fmt.Errorf("%s.%s: field number %d is already used by %s", typeName, goName, number, previous)
		}
		numbers[number] = goName

		if i > 0 {
			b.WriteString("\n")
		}
		writeComment(&b, "  ", field.Doc, goName, name)
		fmt.Fprintf(&b, "  %s %s = %d;\n", protoType, name, number)
	}
	b.WriteString("}\n")
	return b.String(), nil
}

func writeComment(b *strings.Builder, indent string, doc *ast.CommentGroup, goName, protoName string) {
	if doc == nil {
		return
	}
	text := doc.Text()
	if goName != "" {
		if rest, ok := strings.CutPrefix(text, goName+" "); ok {
			text = protoName + " " + rest
		}
	}
	for line := range strings.SplitSeq(strings.TrimRight(text, "\n"), "\n") {
		b.WriteString(strings.TrimRight(indent+"// "+line, " ") + "\n")
	}
}
