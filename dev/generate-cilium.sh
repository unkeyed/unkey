#!/usr/bin/env bash
set -euo pipefail

manifests="$PWD/dev/k8s/manifests"
temporary=$(mktemp -d)
trap 'rm -rf "$temporary"' EXIT

mise exec -- helm template cilium cilium \
  --repo https://helm.cilium.io --version 1.20.2 \
  --namespace kube-system --kube-version 1.37.0 \
  --set operator.replicas=1 \
  --set ipam.operator.clusterPoolIPv4PodCIDRList=10.244.0.0/16 \
  --set hubble.tls.auto.method=cronJob \
  --set hubble.relay.enabled=true --set hubble.ui.enabled=true \
  > "$temporary/manifests.yaml"

for name in cilium hubble; do
  printf '# Generated by mise exec -- bash dev/generate-cilium.sh. Do not edit.\n' > "$manifests/$name.yaml"
done

awk -v directory="$manifests" '
  function write_document() {
    if (document != "") printf "%s", document >> directory "/" target ".yaml"
  }
  /^---$/ { write_document(); document = ""; target = "cilium" }
  /^# Source: cilium\/templates\/hubble-(relay|ui)\// { target = "hubble" }
  { document = document $0 ORS }
  END { write_document() }
' "$temporary/manifests.yaml"

mise -C dev exec -- dprint fmt --config dprint.json k8s/manifests/cilium.yaml k8s/manifests/hubble.yaml
